#!/usr/bin/env python3
"""
Synaptix Robotics — ML-Based Predictive Maintenance of Electrical Motors
train_model.py

Trains the fault classifier OFFLINE and exports it as a plain-C header
(firmware/model.h compatible TREE[] array). The ESP8266 never trains —
it only runs the exported tree, which is why inference costs ~40 us.

Run:
    pip install -r requirements.txt
    python train_model.py                 # synthetic physics-based dataset
    python train_model.py --csv logs.csv  # your own labelled captures

CSV format (header required):
    voltage,current,temperature,vib_rate,vib_peak,label
    5.02,0.41,31.5,4,10,0
label: 0 healthy, 1 overvoltage, 2 undervoltage, 3 overload,
       4 overheat, 5 bearing_wear, 6 imbalance
"""

import argparse
import datetime as dt
import pathlib

import numpy as np
import pandas as pd
from sklearn.metrics import classification_report, confusion_matrix
from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier

RNG = np.random.default_rng(42)

CLASS_ENUM = [
    "CLS_HEALTHY",
    "CLS_OVERVOLTAGE",
    "CLS_UNDERVOLTAGE",
    "CLS_OVERLOAD",
    "CLS_OVERHEAT",
    "CLS_BEARING_WEAR",
    "CLS_IMBALANCE",
]
FEATURES = ["voltage", "current", "temperature", "vib_rate", "vib_peak", "power"]

# Operating envelope of the 6 V DC bench motor used in this build.
# (low, high) per class, matching the firmware thresholds in config.h
PROFILES = {
    0: dict(v=(4.6, 5.9),  i=(0.15, 0.95), t=(26, 44),  vib=(0, 14)),    # healthy
    1: dict(v=(6.05, 9.5), i=(0.5, 1.6),   t=(30, 58),  vib=(5, 30)),    # overvoltage
    2: dict(v=(2.2, 3.49), i=(0.1, 0.8),   t=(26, 42),  vib=(0, 16)),    # undervoltage
    3: dict(v=(4.5, 6.0),  i=(1.25, 2.6),  t=(35, 54),  vib=(6, 26)),    # overload
    4: dict(v=(4.5, 6.0),  i=(0.4, 1.1),   t=(55.5, 85), vib=(3, 22)),   # overheat
    5: dict(v=(4.6, 5.9),  i=(0.3, 1.1),   t=(32, 52),  vib=(18.5, 34)), # bearing wear
    6: dict(v=(4.6, 5.9),  i=(0.3, 1.15),  t=(32, 52),  vib=(35.5, 70)), # imbalance
}
SAMPLES_PER_CLASS = 2500


def synth() -> pd.DataFrame:
    """Build a labelled dataset from the per-class operating envelopes."""
    rows = []
    for label, p in PROFILES.items():
        n = SAMPLES_PER_CLASS
        v = RNG.uniform(*p["v"], n)
        i = RNG.uniform(*p["i"], n)
        t = RNG.uniform(*p["t"], n)
        vib = RNG.uniform(*p["vib"], n)
        # vib_peak: burst density inside the second, correlated with vib_rate
        peak = np.clip(vib * RNG.uniform(1.0, 1.9, n), 0, 120)
        # sensor noise so the tree does not learn razor-thin boundaries
        v += RNG.normal(0, 0.05, n)
        i += RNG.normal(0, 0.03, n)
        t += RNG.normal(0, 0.4, n)
        vib += RNG.normal(0, 0.8, n)
        rows.append(pd.DataFrame({
            "voltage": v, "current": i, "temperature": t,
            "vib_rate": np.clip(vib, 0, None), "vib_peak": peak,
            "power": v * i, "label": label,
        }))
    return pd.concat(rows, ignore_index=True).sample(frac=1, random_state=7)


def export_header(clf, path: pathlib.Path, version: str) -> None:
    """Emit the TREE[] node array in the exact layout firmware/model.h uses."""
    t = clf.tree_
    lines = []
    for n in range(t.node_count):
        if t.children_left[n] == -1:                      # leaf
            probs = t.value[n][0] / t.value[n][0].sum()
            cls = int(np.argmax(probs))
            conf = int(round(float(probs[cls]) * 1000))
            lines.append(
                f"  /* {n:<3} */ {{ -1,  0.000f, -1, -1, "
                f"{CLASS_ENUM[cls]}, {conf} }},"
            )
        else:
            lines.append(
                f"  /* {n:<3} */ {{ {t.feature[n]:>2},"
                f" {t.threshold[n]:8.3f}f, {t.children_left[n]:>3},"
                f" {t.children_right[n]:>3},  0,   0 }},"
            )
    body = "\n".join(lines).rstrip(",")
    path.write_text(
        "/* AUTO-GENERATED by ml/train_model.py — do not edit by hand.\n"
        f" * model {version}   exported {dt.date.today()}\n"
        f" * nodes {t.node_count}   depth {clf.get_depth()}\n"
        " * Paste this array over TREE[] in firmware/model.h, and update\n"
        " * MODEL_VERSION / MODEL_TRAINED to match.\n"
        " */\n\n"
        "static const TreeNode TREE[] = {\n" + body + "\n};\n",
        encoding="utf-8",
    )


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", help="labelled capture instead of synthetic data")
    ap.add_argument("--depth", type=int, default=5)
    ap.add_argument("--version", default="dt-v1.3.0")
    ap.add_argument("--out", default="model_generated.h")
    args = ap.parse_args()

    df = pd.read_csv(args.csv) if args.csv else synth()
    if "power" not in df:
        df["power"] = df["voltage"] * df["current"]

    X, y = df[FEATURES].to_numpy(), df["label"].to_numpy()
    Xtr, Xte, ytr, yte = train_test_split(
        X, y, test_size=0.25, random_state=11, stratify=y
    )

    clf = DecisionTreeClassifier(
        max_depth=args.depth,
        min_samples_leaf=25,
        class_weight="balanced",
        random_state=11,
    ).fit(Xtr, ytr)

    print(f"\nrows {len(df)}   depth {clf.get_depth()}   "
          f"leaves {clf.get_n_leaves()}   test acc {clf.score(Xte, yte):.4f}\n")
    print(classification_report(
        yte, clf.predict(Xte),
        target_names=[c.replace("CLS_", "") for c in CLASS_ENUM], digits=3))
    print("confusion matrix\n", confusion_matrix(yte, clf.predict(Xte)))
    print("\nfeature importance")
    for name, imp in sorted(zip(FEATURES, clf.feature_importances_),
                            key=lambda p: -p[1]):
        print(f"  {name:<12} {imp:.3f}")

    out = pathlib.Path(args.out)
    export_header(clf, out, args.version)
    print(f"\nwrote {out.resolve()}  ->  copy TREE[] into firmware/model.h")


if __name__ == "__main__":
    main()
