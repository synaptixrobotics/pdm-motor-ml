#!/usr/bin/env python3
"""
Synaptix Robotics - build a single-file dashboard.

Inlines dashboard/styles.css and dashboard/app.js into dashboard/index.html
and writes dashboard-local.html at the project root.

That one file needs no web server, no npm, no Vercel: double-click it and
it opens from file://, which can talk to the ESP8266 over plain HTTP
because the firmware sends Access-Control-Allow-Origin: *.

    python tools/build_local_dashboard.py
"""
import io
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
html = (root / "dashboard" / "index.html").read_text(encoding="utf-8")
css = (root / "dashboard" / "styles.css").read_text(encoding="utf-8")
js = (root / "dashboard" / "app.js").read_text(encoding="utf-8")

html, n_css = re.subn(
    r'<link rel="stylesheet" href="styles\.css">',
    "<style>\n" + css + "\n</style>",
    html,
)
html, n_js = re.subn(
    r'<script src="app\.js"></script>',
    "<script>\n" + js + "\n</script>",
    html,
)
assert n_css == 1, "stylesheet link not found"
assert n_js == 1, "script tag not found"

banner = (
    "<!--\n"
    "  Synaptix Robotics - Motor Health Monitor (single-file build)\n"
    "  GENERATED by tools/build_local_dashboard.py - do not edit directly.\n"
    "  Edit dashboard/*, then re-run the script.\n"
    "\n"
    "  Open this file directly in a browser. No server needed.\n"
    "  Type the ESP8266's IP in the box and press Connect.\n"
    "-->\n"
)
out = root / "dashboard-local.html"
out.write_text(banner + html, encoding="utf-8")

size = out.stat().st_size
print("wrote %s  (%.1f KB, css %d B, js %d B)" % (out.name, size / 1024, len(css), len(js)))
